import uuid
from datetime import datetime

from pydantic import BaseModel, Field


class ScanRequest(BaseModel):
    resolution: int = Field(
        default=300, ge=75, le=600, description="Scan resolution in dpi.", examples=[300]
    )
    mode: str = Field(
        default="Color",
        pattern="^(Color|Gray|Lineart)$",
        description="Colour mode.",
        examples=["Color"],
    )
    format: str = Field(
        default="pdf",
        pattern="^(png|jpeg|tiff|pdf)$",
        description="Output file format.",
        examples=["pdf"],
    )
    source: str = Field(
        default="Flatbed",
        pattern="^(Flatbed|ADF)$",
        description="Paper source: the glass or the automatic document feeder.",
        examples=["Flatbed"],
    )
    # F26: lets the client generate the id up front and subscribe to its
    # progress WebSocket *before* POSTing, instead of only learning the id
    # after the (synchronous) scan has already finished. Backend-generated
    # when omitted.
    scan_id: uuid.UUID | None = Field(
        default=None,
        description="Optional client-generated id, so the progress WebSocket can be opened before "
            "the request. Generated by the server when omitted.",
        examples=["3f2b8c1e-9a4d-4e57-8f0a-1c2d3e4f5a6b"],
    )


class ScanBatchRequest(ScanRequest):
    source: str = Field(
        default="ADF", description="Paper source; batches default to the feeder.", examples=["ADF"]
    )


class ScanResponse(BaseModel):
    id: int = Field(description="Database id.", examples=[12])
    scan_id: str = Field(
        description="Public scan identifier (UUID), used in all scan URLs.",
        examples=["3f2b8c1e-9a4d-4e57-8f0a-1c2d3e4f5a6b"],
    )
    status: str = Field(
        description="Lifecycle state: scanning, completed, failed or cancelled.",
        examples=["completed"]
    )
    resolution: int = Field(description="Resolution in dpi.", examples=[300])
    mode: str = Field(description="Colour mode.", examples=["Color"])
    format: str = Field(description="Stored file format (may differ from the request, e.g. a "
        "feeder scan is always pdf).", examples=["pdf"])
    source: str = Field(
        description="Paper source actually used (Flatbed or ADF).", examples=["Flatbed"]
    )
    page_count: int = Field(description="Number of pages in the file (live sheet count while "
        "scanning a feeder batch).", examples=[1])
    progress_pct: int | None = Field(default=None, description="Scan progress 0-100 while "
        "status is scanning and the scan runs in this process; null otherwise.", examples=[40])
    file_size: int | None = Field(
        description="File size in bytes once completed.", examples=[482113]
    )
    error_message: str | None = Field(description="User-facing failure reason when status is "
        "failed.", examples=[None])
    created_at: datetime = Field(description="When the scan was started.")
    completed_at: datetime | None = Field(description="When the scan finished.")
    duplex_merged: bool = Field(default=False, description="True for a merged double-sided scan, "
        "or for fronts already merged with backs.")
    duplex_source_scan_id: str | None = Field(default=None, description="For a back-side scan, the "
        "scan_id of the fronts it belongs to.")

    model_config = {"from_attributes": True}


def overlay_live(resp: "ScanResponse") -> "ScanResponse":
    """Overlay live progress/page_count from the scan registry onto a scanning row."""
    if resp.status == "scanning":
        from app.services import scan_tasks

        pct, pages = scan_tasks.snapshot(resp.scan_id)
        resp.progress_pct = pct
        if pages is not None:
            resp.page_count = pages
    return resp


def serialize_scan_job(scan) -> dict:
    """Serialize a ScanJob ORM object into the exact JSON shape returned by the
    scan list endpoint (``ScanResponse``).

    Reused for WebSocket broadcasts so realtime payloads match the REST shape
    field-for-field.
    """
    resp = overlay_live(ScanResponse.model_validate(scan, from_attributes=True))
    return resp.model_dump(mode="json")


